//! Refreshes the "Detailed results" block of the repository `README.md`
//! from a `bench-compare` result document: one table per family at the
//! largest size where dir-24-8 was measured, with a 🏆 on the best value of
//! every column. Only the block between [`START`] and [`END`] changes.
//!
//! `README` (`BENCH_README`) decides when a run writes it: `auto` (default)
//! for complete runs of the default structure selection up to at least 1M
//! entries, `1` always, `0` never; `REPORT_ONLY=1` applies it too.

use std::path::Path;

use crate::adapter::Api;
use crate::bench::{Measure, Op, RunResult, Status};
use crate::dataset::{Dist, Family};
use crate::report::Results;

/// The structures tab of the `bench-compare` report of the latest release
/// on the GitHub Pages site (.github/workflows/pages.yml).
const ONLINE_REPORT: &str =
    "https://0x00f6.github.io/dir-24-8/bench-compare/report.html#structures";

/// First line of the generated block.
pub const START: &str = "<!-- bench-compare:details:start -->";
/// Last line of the generated block.
pub const END: &str = "<!-- bench-compare:details:end -->";

/// Whether `mode` (`BENCH_README`) lets this result document update the
/// README: `auto` needs a complete run of the default selection reaching 1M
/// entries, so smoke runs never overwrite the published tables.
pub fn wanted(mode: &str, r: &Results) -> bool {
    match mode {
        "1" => true,
        "0" => false,
        _ => {
            let s = &r.meta.settings;
            r.meta.complete
                && (s.engines.is_empty() || s.engines == ["default"])
                && s.sizes.iter().max().is_some_and(|&m| m >= 1_000_000)
        }
    }
}

/// Replaces the generated block of `readme`; `Ok(false)` when unchanged.
pub fn update(readme: &Path, r: &Results) -> Result<bool, String> {
    crate::libcmp::readme::replace_block(readme, START, END, &details(r)?)
}

/// Columns of a family table.
#[derive(Clone, Copy)]
enum Col {
    Rate { op: Op, threads: usize },
    P50,
    P99,
    Footprint,
    Build,
}

impl Col {
    fn higher_is_better(self) -> bool {
        matches!(self, Col::Rate { .. })
    }
}

/// The generated Markdown: run description, then one table per family.
pub fn details(r: &Results) -> Result<String, String> {
    let s = &r.meta.settings;
    let env = &r.meta.env;
    let dist = if s.dists.contains(&Dist::Random) {
        Dist::Random
    } else {
        *s.dists.first().ok_or("no distribution measured")?
    };
    let tmax = s.threads.iter().copied().max().unwrap_or(1);
    let batch = s.batch.first().copied();
    let date = utc_date(env.timestamp_unix);
    let kernel = if env.batch_kernel.is_empty() {
        "?"
    } else {
        env.batch_kernel.as_str()
    };
    let mut out = format!(
        "- **Run**: `make bench-compare`, structures part, {date}, {}, dir-24-8 batch kernel {kernel}\n",
        env.cpu
    );
    if !r.meta.complete {
        out.push_str("- **Status**: partial (the run was interrupted)\n");
    }
    out.push_str(&format!(
        "- **Workload**: {} distribution ({} % hits), {} queries, batches of {}\n",
        dist.name(),
        trim(f64::from(s.hit_permille) / 10.0),
        thousands(s.queries as u64),
        batch.map_or("-".into(), |b| b.to_string())
    ));
    out.push_str(&format!(
        "- **Units**: M/s = millions of addresses per second (full `Option<LookupMatch>` results); \
         p50/p99 of isolated single lookups, one thread\n\
         - **Footprint**: includes the prefix + payload table competitors need\n\
         - **Reading**: 🏆 marks the best value of each column; rows are sorted by \
         single-thread batch throughput\n\
         - **Full report**: [report.html, structures tab]({ONLINE_REPORT}) (every size, distribution and thread \
         count; `benchmarks/reports/` locally)\n\n\
         <!-- Generated by `make bench-compare` (README): do not edit by hand. -->\n",
    ));

    let mut cols = vec![
        (
            "lookup 1T".to_string(),
            Col::Rate {
                op: Op::Lookup,
                threads: 1,
            },
        ),
        (
            "batch 1T".to_string(),
            Col::Rate {
                op: Op::Batch,
                threads: 1,
            },
        ),
        (
            "exists 1T".to_string(),
            Col::Rate {
                op: Op::Exists,
                threads: 1,
            },
        ),
    ];
    if tmax > 1 {
        cols.push((
            format!("lookup {tmax}T"),
            Col::Rate {
                op: Op::Lookup,
                threads: tmax,
            },
        ));
        cols.push((
            format!("batch {tmax}T"),
            Col::Rate {
                op: Op::Batch,
                threads: tmax,
            },
        ));
    }
    cols.extend([
        ("p50".to_string(), Col::P50),
        ("p99".to_string(), Col::P99),
        ("footprint".to_string(), Col::Footprint),
        ("build".to_string(), Col::Build),
    ]);

    let legacy = r.engines.iter().any(|e| {
        matches!(
            e.name.as_str(),
            "dir-24-8[avx2]" | "dir-24-8[avx512]" | "dir-24-8[neon]"
        )
    });
    for fam in [Family::Ipv4, Family::Ipv6] {
        if !s.families.contains(&fam) {
            continue;
        }
        // Largest size at which dir-24-8 has results for this family.
        let Some(size) = r
            .runs
            .iter()
            .filter(|run| run.family == fam && run.engine == "dir-24-8" && run.status == Status::Ok)
            .map(|run| run.size)
            .max()
        else {
            continue;
        };
        let mut rows: Vec<(String, Vec<Option<f64>>)> = Vec::new();
        let mut skipped = Vec::new();
        for e in &r.engines {
            let Some(run) = r
                .runs
                .iter()
                .find(|run| run.family == fam && run.size == size && run.engine == e.name)
            else {
                continue;
            };
            if run.status != Status::Ok {
                if run.status != Status::NotApplicable {
                    skipped.push(format!(
                        "{} ({})",
                        label(&e.name, kernel, legacy),
                        status_name(&run.status)
                    ));
                }
                continue;
            }
            let mut name = format!("`{}`", label(&e.name, kernel, legacy));
            if e.lookup == Api::Unsupported {
                name.push_str(" (exists only)");
            }
            let values = cols
                .iter()
                .map(|(_, c)| value(run, *c, dist, batch))
                .collect();
            rows.push((name, values));
        }
        rows.sort_by(|a, b| {
            let key =
                |r: &(String, Vec<Option<f64>>)| (r.1[1].unwrap_or(-1.0), r.1[0].unwrap_or(-1.0));
            key(b)
                .partial_cmp(&key(a))
                .unwrap_or(std::cmp::Ordering::Equal)
        });
        let best: Vec<Option<f64>> = (0..cols.len())
            .map(|i| {
                rows.iter()
                    .filter_map(|r| r.1[i])
                    .fold(None, |acc: Option<f64>, v| {
                        Some(match acc {
                            None => v,
                            Some(b) if cols[i].1.higher_is_better() => b.max(v),
                            Some(b) => b.min(v),
                        })
                    })
            })
            .collect();

        out.push_str(&format!("\n| {}, {} |", fam.label(), size_label(size)));
        for (h, _) in &cols {
            out.push_str(&format!(" {h} |"));
        }
        out.push_str("\n|---|");
        out.push_str(&"---|".repeat(cols.len()));
        out.push('\n');
        for (name, values) in &rows {
            out.push_str(&format!("| {name} |"));
            for (i, v) in values.iter().enumerate() {
                let cell = match v {
                    None => "—".to_string(),
                    Some(v) => {
                        let text = format_value(*v, cols[i].1);
                        if Some(*v) == best[i] {
                            format!("🏆 **{text}**")
                        } else {
                            text
                        }
                    }
                };
                out.push_str(&format!(" {cell} |"));
            }
            out.push('\n');
        }
        if !skipped.is_empty() {
            out.push_str(&format!(
                "\nNot measured at {} ({}): {}.\n",
                size_label(size),
                fam.label(),
                skipped.join(", ")
            ));
        }
    }
    Ok(out)
}

/// Report label of an engine (the HTML report uses the same names).
fn label(name: &str, kernel: &str, legacy: bool) -> String {
    let isa = |k: &str| match k {
        "avx512" => "AVX-512".to_string(),
        "avx2" => "AVX2".to_string(),
        "neon" => "NEON".to_string(),
        other => other.to_string(),
    };
    match name {
        "dir-24-8" if legacy => format!("dir-24-8 (SIMD {})", isa(kernel)),
        "dir-24-8" if kernel == "scalar" => "dir-24-8 (batch-simd, no SIMD kernel)".into(),
        "dir-24-8" => format!("dir-24-8 (SIMD {} batches)", isa(kernel)),
        "dir-24-8[scalar]" => "dir-24-8 (scalar)".into(),
        n if n.starts_with("dir-24-8[") => {
            format!(
                "dir-24-8 (SIMD {}, forced)",
                isa(&n["dir-24-8[".len()..n.len() - 1])
            )
        }
        n => n.into(),
    }
}

fn status_name(s: &Status) -> &'static str {
    match s {
        Status::Ok => "ok",
        Status::NotApplicable => "not applicable",
        Status::MemoryLimit => "memory limit",
        Status::Timeout => "timeout",
        Status::Budget => "time budget",
        Status::Invalid => "invalid results",
        Status::Failed => "failed",
    }
}

fn measure(
    run: &RunResult,
    op: Op,
    threads: usize,
    dist: Dist,
    batch: Option<usize>,
) -> Option<&Measure> {
    run.measures.iter().find(|m| {
        m.op == op
            && m.dist == dist
            && m.threads == threads
            && (op != Op::Batch || m.batch == batch)
    })
}

fn value(run: &RunResult, col: Col, dist: Dist, batch: Option<usize>) -> Option<f64> {
    let positive = |v: f64| (v > 0.0).then_some(v);
    match col {
        Col::Rate { op, threads } => {
            measure(run, op, threads, dist, batch).map(|m| m.throughput.median)
        }
        Col::P50 => measure(run, Op::Lookup, 1, dist, None).and_then(|m| positive(m.latency.p50)),
        Col::P99 => measure(run, Op::Lookup, 1, dist, None).and_then(|m| positive(m.latency.p99)),
        Col::Footprint => run.memory.as_ref().map(|m| m.footprint as f64),
        Col::Build => run.build_s,
    }
}

fn format_value(v: f64, col: Col) -> String {
    match col {
        Col::Rate { .. } => {
            let m = v / 1e6;
            if m >= 10.0 {
                format!("{m:.0} M/s")
            } else {
                format!("{m:.1} M/s")
            }
        }
        Col::P50 | Col::P99 if v >= 1_000.0 => format!("{:.2} µs", v / 1_000.0),
        Col::P50 | Col::P99 => format!("{v:.0} ns"),
        Col::Footprint => bytes(v),
        Col::Build if v >= 1.0 => format!("{v:.1} s"),
        Col::Build => format!("{v:.2} s"),
    }
}

fn bytes(v: f64) -> String {
    const K: f64 = 1024.0;
    if v < K {
        format!("{v:.0} B")
    } else if v < K * K {
        format!("{:.0} KiB", v / K)
    } else if v < K * K * K {
        format!("{:.0} MiB", v / (K * K))
    } else {
        format!("{:.2} GiB", v / (K * K * K))
    }
}

fn trim(v: f64) -> String {
    let s = format!("{v:.1}");
    s.strip_suffix(".0").map_or(s.clone(), str::to_string)
}

/// `1048576` -> `1 048 576`.
fn thousands(n: u64) -> String {
    let digits = n.to_string();
    let mut out = String::new();
    for (i, c) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i).is_multiple_of(3) {
            out.push(' ');
        }
        out.push(c);
    }
    out
}

fn size_label(n: usize) -> String {
    match n {
        n if n >= 1_000_000 && n.is_multiple_of(1_000_000) => format!("{}M", n / 1_000_000),
        n if n >= 1_000 && n.is_multiple_of(1_000) => format!("{}k", n / 1_000),
        n => n.to_string(),
    }
}

/// `YYYY-MM-DD` (UTC) of a Unix timestamp.
fn utc_date(unix: u64) -> String {
    let z = (unix / 86_400) as i64 + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = yoe + era * 400 + i64::from(m <= 2);
    format!("{y:04}-{m:02}-{d:02}")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn formats() {
        assert_eq!(
            format_value(
                53e6,
                Col::Rate {
                    op: Op::Batch,
                    threads: 1
                }
            ),
            "53 M/s"
        );
        assert_eq!(
            format_value(
                9.7e6,
                Col::Rate {
                    op: Op::Batch,
                    threads: 1
                }
            ),
            "9.7 M/s"
        );
        assert_eq!(format_value(716.0, Col::P99), "716 ns");
        assert_eq!(format_value(1_260.0, Col::P99), "1.26 µs");
        assert_eq!(
            format_value(842.0 * 1024.0 * 1024.0, Col::Footprint),
            "842 MiB"
        );
        assert_eq!(
            format_value(8.54 * 1024.0 * 1024.0 * 1024.0, Col::Footprint),
            "8.54 GiB"
        );
        assert_eq!(format_value(0.37, Col::Build), "0.37 s");
        assert_eq!(format_value(8.9, Col::Build), "8.9 s");
        assert_eq!(size_label(5_000_000), "5M");
        assert_eq!(thousands(1_048_576), "1 048 576");
        assert_eq!(trim(50.0), "50");
        assert_eq!(utc_date(1_794_000_448), "2026-11-06");
    }

    #[test]
    fn labels() {
        assert_eq!(
            label("dir-24-8", "avx512", false),
            "dir-24-8 (SIMD AVX-512 batches)"
        );
        assert_eq!(label("dir-24-8", "avx512", true), "dir-24-8 (SIMD AVX-512)");
        assert_eq!(
            label("dir-24-8", "scalar", false),
            "dir-24-8 (batch-simd, no SIMD kernel)"
        );
        assert_eq!(
            label("dir-24-8[scalar]", "avx512", false),
            "dir-24-8 (scalar)"
        );
        assert_eq!(
            label("dir-24-8[avx2]", "avx512", true),
            "dir-24-8 (SIMD AVX2, forced)"
        );
        assert_eq!(
            label("poptrie(s=18,k=6)", "avx2", false),
            "poptrie(s=18,k=6)"
        );
    }
}
